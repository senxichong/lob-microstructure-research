class Distribution:
    """Exact event-weighted histogram; scales with distinct values, not raw rows."""

    def __init__(self):
        self.counts = Counter()

    def add(self, value):
        if value is not None:
            self.counts[value] += 1

    def result(self):
        total = sum(self.counts.values())
        if not total:
            return {"n": 0}
        items = sorted(self.counts.items())
        out = {
            "n": total,
            "min": items[0][0],
            "max": items[-1][0],
            "mean": sum(v * n for v, n in items) / total,
        }
        # Discrete nearest-rank empirical quantiles, not interpolation.
        for q in (0.01, 0.5, 0.95, 0.99):
            rank = max(1, math.ceil(q * total))
            cumulative = 0
            for value, n in items:
                cumulative += n
                if cumulative >= rank:
                    out[f"p{int(q * 100):02}"] = value
                    break
        return out


def book_row(e, ns, snapshot, book, issues):
    row = {
        "source_row": e.row,
        "timestamp": ns,
        "source_time_ms": e.time_ms,
        "event_type": e.kind,
        "bid_levels_available": len(book.levels["B"]),
        "ask_levels_available": len(book.levels["S"]),
        "issues": issues,
        "research_eligible": not issues,
        **diagnostics(snapshot),
    }
    for name, key in (("bid", "bids"), ("ask", "asks")):
        levels = snapshot[key]
        row[f"best_{name}_price"] = price_dollars(levels[0][0]) if levels else None
        row[f"best_{name}_size"] = levels[0][1] if levels else None
        for level, (price, size) in enumerate(levels, 1):
            row.update(
                {
                    f"{name}_price_units_{level}": price,
                    f"{name}_price_{level}": price_dollars(price),
                    f"{name}_size_{level}": size,
                }
            )
    return row


def top(snapshot, side):
    return snapshot[side][0][0] if snapshot[side] else None


def audit_aggregate(book):
    expected = {"B": Counter(), "S": Counter()}
    for order in book.orders.values():
        if order.symbol == book.symbol:
            expected[order.side][order.price] += order.size
    if any(dict(expected[side]) != book.levels[side] for side in ("B", "S")):
        raise ValueError("independent order-sum audit disagrees with price-level cache")


def write_traces(path, traces, raw_hash):
    lines = [
        "# Real event traces",
        "",
        f"Raw ZIP SHA-256: `{raw_hash}`.",
        "",
        "Local-only data excerpts; excluded from Git. Prices below are integer USD / 10,000 units; quantities are shares.",
        "Each before-state precedes this source row; each after-state includes it. Row IDs are file positions, not exchange sequence numbers.",
        "",
        "| Row | UTC | Type | Side | Price units | Shares | Order before -> after | BBO before -> after |",
        "|---:|---|---|---|---:|---:|---|---|",
    ]
    for t in traces:
        e = t["event"]
        lines.append(
            f"| {e['source_row']} | {t['timestamp']} | {e['event_type']} | {e['side']} | {e['price_units']} | {e['size']} | {t['order_size_before']} -> {t['order_size_after']} | {t['best_bid_ask_before']} -> {t['best_bid_ask_after']} |"
        )
    lines += [""]
    for trace in traces:
        event = trace["event"]
        lines += [
            f"## Source row {event['source_row']} / {event['event_type']} / {trace['timestamp']}",
            "",
            "```json",
            json.dumps(trace, indent=2),
            "```",
            "",
        ]
    path.write_text("\n".join(lines), encoding="utf-8")


def quality_markdown(stats):
    lines = [
        "# Measured data quality",
        "",
        "Generated by `lob-phase1`; no predictive experiments.",
        "",
        "Counts distinguish all source messages, the selected instrument across the source day, and retained RTH observations.",
        "",
        "```json",
        json.dumps({k: v for k, v in stats.items() if k != "distributions"}, indent=2),
        "```",
        "",
        "## Diagnostic distributions",
        "",
        "Event-weighted, not time-weighted. Quantiles use nearest ranks. No future data are used.",
        "",
        "| Quantity | n | min | p01 | p50 | p95 | p99 | max | mean |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, values in stats["distributions"].items():
        lines.append(
            "| "
            + name
            + " | "
            + " | ".join(
                str(values.get(k, "NA"))
                for k in ("n", "min", "p01", "p50", "p95", "p99", "max", "mean")
            )
            + " |"
        )
    lines += [
        "",
        "Missing feed messages cannot be certified absent: this file has no transport sequence numbers.",
        "Order references are not event sequences. Unknown references, nonincreasing add references, malformed lines and over-reductions cause a logged abort.",
        "Locked/crossed states are retained with issues and research_eligible=false; no silent deletion or price repair.",
        "All premarket events seed the book. The output window is half-open and does not claim independently verified halt/auction status.",
        "The encoding quantum is $0.0001. Historical venue minimum tick is not established by this file; penny-grid deviations are descriptive, not errors.",
        "Trade breaks are an append-only correction table. Original trade rows are never retrospectively erased.",
        "Peak RSS is the OS peak working set when available (otherwise sampled RSS). Throughput excludes download and report serialization.",
        "",
    ]
    return "\n".join(lines)


def run(config_path="config.yaml"):
    config_path = Path(config_path)
    cfg = yaml.safe_load(config_path.read_text())
    out, reports = Path(cfg["output_dir"]), Path(cfg["reports_dir"])
    out.mkdir(parents=True, exist_ok=True)
    reports.mkdir(parents=True, exist_ok=True)
    status_path = reports / "run_status.json"
    status_path.write_text(
        json.dumps({"status": "incomplete", "config_sha256": sha256(config_path)})
    )
    logging.basicConfig(
        filename=reports / "ingestion.log",
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
    )
    raw = fetch(cfg["source_url"], cfg["raw_path"], "DATA_MANIFEST.json")
    begin, end = clock_ms(cfg["session_start"]), clock_ms(cfg["session_end"])
    if begin >= end or cfg["depth"] <= 0 or cfg["batch_rows"] <= 0 or cfg["price_grid_units"] <= 0:
        raise ValueError("invalid session/depth/batch/grid configuration")
    epoch = day_epoch_ns(cfg["date"], cfg["timezone"])
    lineage = {
        "raw_sha256": raw["sha256"],
        "member": cfg["member"],
        "config_sha256": sha256(config_path),
        "symbol": cfg["symbol"],
        "date": cfg["date"],
        "ordering": "source_row",
        "timestamp_timezone": "UTC",
        "phase": 1,
    }
    writers = {
        name: BatchWriter(out / f"{name}.parquet.part", schema, cfg["batch_rows"])
        for name, schema in schemas(cfg["depth"], lineage).items()
    }
    book, ordering = OrderBook(cfg["symbol"]), Ordering()
    stats = {
        "symbol": cfg["symbol"],
        "source_date": cfg["date"],
        "lineage": lineage,
        "source_messages": 0,
        "selected_all_day_events": 0,
        "rth_events": 0,
        "selected_before_window_events": 0,
        "selected_after_window_events": 0,
        "timestamp_resolution_ms": 1,
        "source_adjacent_duplicate_timestamps": 0,
        "source_timestamp_regressions": 0,
        "rth_adjacent_duplicate_timestamps": 0,
        "source_row_order_violations": 0,
        "exchange_sequence_violations": "not detectable: sequence absent",
        "missing_feed_messages": "not certifiable: transport sequence absent",
        "parse_failures": 0,
        "reconstruction_failures": 0,
        "aggregate_audits": 0,
        "all_day_book_issue_states": 0,
        "rth_book_issue_states": 0,
        "rth_book_changes": 0,
        "rth_bbo_changes": 0,
        "rth_spread_changes": 0,
        "rth_visible_price_off_penny_grid": 0,
        "source_terminal_blank_lines": 0,
        "source_frame_lengths": {},
        "source_display_codes": {},
        "source_system_events": [],
        "source_broken_trades": 0,
        "rth_trade_breaks": 0,
    }
    source_types, selected_types, rth_types = Counter(), Counter(), Counter()
    all_issues, rth_issues, depths, displays, frame_lengths = (
        Counter(),
        Counter(),
        Counter(),
        Counter(),
        Counter(),
    )
    distribution = {
        key: Distribution()
        for key in (
            "spread_usd",
            "relative_spread",
            "midprice_usd",
            "best_bid_size_shares",
            "best_ask_size_shares",
            "interarrival_ms",
            "trade_size_shares",
            "updates_per_second_active_seconds",
        )
    }
    updates_second = Counter()
    selected_match = {}
    all_match = set()
    broken_match = set()
    symbols = set()
    trace_counts, traces = Counter(), []
    previous_snapshot = book.snapshot(cfg["depth"])
    previous_selected_row = None
    previous_rth_ms = None
    previous_rth_spread = None
    selected_price_gcd = 0
    last_row = None
    blank_seen = False
    hasher = hashlib.sha256()
    started = time.perf_counter()
    proc = psutil.Process()
    peak_rss = proc.memory_info().rss
    failure_path = reports / "failures.jsonl"
    # A fresh run has its own failure ledger; raw input remains untouched.
    failure_path.write_text("")
    (reports / "book_issues.jsonl").write_text("")
    try:
        with zipfile.ZipFile(cfg["raw_path"]) as archive:
            info = archive.getinfo(cfg["member"])
            stats["raw_member_bytes"] = info.file_size
            stats["zip_member_datetime"] = list(info.date_time)
            with io.BufferedReader(archive.open(info), buffer_size=1024 * 1024) as stream:
                for row_no, raw_line in enumerate(stream, 1):
                    hasher.update(raw_line)
                    last_row = row_no
                    # Sample includes a terminal blank line; retain/count framing,
                    # accept only trailing blank lines, never silently skip mid-file.
                    if raw_line in {b"\n", b"\r\n"}:
                        blank_seen = True
                        stats["source_terminal_blank_lines"] += 1
                        continue
                    if blank_seen:
                        raise ValueError("nonterminal blank source line")
                    try:
                        e = parse_line(raw_line, row_no)
                    except Exception:
                        stats["parse_failures"] += 1
                        raise
                    try:
                        regressed, duplicate = ordering.observe(e)
                    except Exception:
                        stats["source_row_order_violations"] += 1
                        raise
                    stats["source_messages"] += 1
                    stats["source_timestamp_regressions"] += regressed
                    stats["source_adjacent_duplicate_timestamps"] += duplicate
                    source_types[e.kind] += 1
                    frame_lengths[
                        f"{e.kind}:{len(raw_line.rstrip(chr(10).encode()).rstrip(chr(13).encode()))}"
                    ] += 1
                    stats.setdefault("source_first_timestamp", iso_utc(epoch + e.time_ms * 1000000))
                    stats["source_last_timestamp"] = iso_utc(epoch + e.time_ms * 1000000)
                    if e.kind == "A":
                        symbols.add(e.symbol)
                        displays[e.display] += 1
                    if e.kind == "S":
                        stats["source_system_events"].append(
                            {"row": e.row, "time_ms": e.time_ms, "code": e.system_code}
                        )
                    before = previous_snapshot
                    existing = book.orders.get(e.order_id)
                    before_order_size = existing.size if existing else None
                    try:
                        affected = book.apply(e)
                    except Exception:
                        stats["reconstruction_failures"] += 1
                        raise
                    if e.kind in {"E", "P"}:
                        if e.match_id in all_match:
                            raise ValueError("duplicate match ID")
                        all_match.add(e.match_id)
                        if affected.symbol == cfg["symbol"]:
                            selected_match[e.match_id] = e.row
                    if e.kind == "B":
                        stats["source_broken_trades"] += 1
                        if e.match_id not in all_match or e.match_id in broken_match:
                            raise ValueError("unknown/repeated trade break")
                        broken_match.add(e.match_id)
                    is_selected = affected is not None and affected.symbol == cfg["symbol"]
                    selected_break = e.kind == "B" and e.match_id in selected_match
                    if not is_selected and not selected_break:
                        continue
                    stats["selected_all_day_events"] += 1
                    selected_types[e.kind] += 1
                    after = book.snapshot(cfg["depth"])
                    issues = book_issues(after, cfg["price_grid_units"])
                    stats["all_day_book_issue_states"] += bool(issues)
                    all_issues.update(issues)
                    in_session = begin <= e.time_ms < end
                    stats["selected_before_window_events"] += e.time_ms < begin
                    stats["selected_after_window_events"] += e.time_ms >= end
                    if issues:
                        with (reports / "book_issues.jsonl").open("a") as f:
                            f.write(
                                json.dumps(
                                    {
                                        "source_row": e.row,
                                        "time_ms": e.time_ms,
                                        "in_window": in_session,
                                        "issues": issues,
                                    }
                                )
                                + "\n"
                            )
                    ns = epoch + e.time_ms * 1000000
                    event_row = {
                        "source_row": e.row,
                        "timestamp": ns,
                        "source_time_ms": e.time_ms,
                        "event_type": e.kind,
                        "order_id": e.order_id,
                        "match_id": e.match_id,
                        "side": affected.side if affected else None,
                        "price_units": affected.price if affected else None,
                        "price": price_dollars(affected.price) if affected else None,
                        "size": affected.size if affected else None,
                        "display": affected.display if affected else None,
                        "symbol": cfg["symbol"],
                    }
                    if in_session:
                        stats["rth_events"] += 1
                        rth_types[e.kind] += 1
                        stats.setdefault("rth_first_timestamp", iso_utc(ns))
                        stats["rth_last_timestamp"] = iso_utc(ns)
                        stats["rth_book_issue_states"] += bool(issues)
                        rth_issues.update(issues)
                        changed = before != after
                        stats["rth_book_changes"] += changed
                        stats["rth_bbo_changes"] += (
                            before["bids"][:1] != after["bids"][:1]
                            or before["asks"][:1] != after["asks"][:1]
                        )
                        if changed:
                            updates_second[e.time_ms // 1000] += 1
                        quote = book_row(e, ns, after, book, issues)
                        writers["events"].append(event_row)
                        writers["books"].append(quote)
                        depths[f"{len(after['bids'])}/{len(after['asks'])}"] += 1
                        if previous_rth_ms is not None:
                            distribution["interarrival_ms"].add(e.time_ms - previous_rth_ms)
                            stats["rth_adjacent_duplicate_timestamps"] += (
                                e.time_ms == previous_rth_ms
                            )
                        previous_rth_ms = e.time_ms
                        if previous_rth_spread is not None:
                            stats["rth_spread_changes"] += quote["spread"] != previous_rth_spread
                        previous_rth_spread = quote["spread"]
                        if not issues:
                            for field, key in (
                                ("spread", "spread_usd"),
                                ("relative_spread", "relative_spread"),
                                ("midprice", "midprice_usd"),
                                ("best_bid_size", "best_bid_size_shares"),
                                ("best_ask_size", "best_ask_size_shares"),
                            ):
                                distribution[key].add(quote[field])
                        if e.kind == "A":
                            selected_price_gcd = math.gcd(selected_price_gcd, e.price_units)
                            stats["rth_visible_price_off_penny_grid"] += e.price_units % 100 != 0
                        if e.kind in {"E", "P"}:
                            writers["trades"].append(
                                {
                                    **event_row,
                                    "aggressor_side": None,
                                    "aggressor_basis": "not directly supplied; side is executed resting order",
                                    "pre_quote_source_row": previous_selected_row,
                                    "post_quote_source_row": e.row,
                                    "pre_bid_units": top(before, "bids"),
                                    "pre_ask_units": top(before, "asks"),
                                    "post_bid_units": top(after, "bids"),
                                    "post_ask_units": top(after, "asks"),
                                }
                            )
                            distribution["trade_size_shares"].add(e.size)
                        if selected_break:
                            writers["trade_breaks"].append(
                                {
                                    **event_row,
                                    "original_trade_source_row": selected_match[e.match_id],
                                }
                            )
                            stats["rth_trade_breaks"] += 1
                        if e.kind in {"A", "X", "E", "P"} and trace_counts[e.kind] < 3:
                            side_key = "bids" if affected.side == "B" else "asks"
                            delta = dict(after[side_key]).get(affected.price, 0) - dict(
                                before[side_key]
                            ).get(affected.price, 0)
                            traces.append(
                                {
                                    "timestamp": iso_utc(ns),
                                    "event": event_row,
                                    "before_source_row": previous_selected_row,
                                    "book_before": before,
                                    "book_after": after,
                                    "best_bid_ask_before": [
                                        top(before, "bids"),
                                        top(before, "asks"),
                                    ],
                                    "best_bid_ask_after": [top(after, "bids"), top(after, "asks")],
                                    "order_size_before": before_order_size,
                                    "order_size_after": book.orders[e.order_id].size
                                    if e.order_id in book.orders
                                    else None,
                                    "displayed_level_delta_in_top_n": delta,
                                    "interpretation": {
                                        "A": "Add increases displayed shares; deeper prices may be outside saved top N.",
                                        "X": "Cancel reduces shares; zero remaining removes the order.",
                                        "E": "Visible execution reduces the referenced resting order at its limit price.",
                                        "P": "Hidden execution is a trade and leaves displayed depth unchanged.",
                                    }[e.kind],
                                }
                            )
                            trace_counts[e.kind] += 1
                    previous_snapshot, previous_selected_row = after, e.row
                    if stats["selected_all_day_events"] % 50000 == 0:
                        audit_aggregate(book)
                        stats["aggregate_audits"] += 1
                        peak_rss = max(peak_rss, proc.memory_info().rss)
                        print(
                            f"Replayed {stats['source_messages']:,} source messages; {stats['rth_events']:,} retained events",
                            flush=True,
                        )
        if not book.ended:
            raise ValueError("source ended without End of Day")
        audit_aggregate(book)
        stats["aggregate_audits"] += 1
    except Exception as exc:
        with failure_path.open("a") as f:
            f.write(json.dumps({"source_row": last_row, "error": str(exc), "stats": stats}) + "\n")
        logging.exception("Ingestion failed at source row %s", last_row)
        raise
    finally:
        for writer in writers.values():
            writer.close()
    elapsed = time.perf_counter() - started
    stats["processing_seconds"] = elapsed
    stats["source_messages_per_second"] = stats["source_messages"] / elapsed
    mem = proc.memory_info()
    stats["peak_rss_bytes"] = max(peak_rss, getattr(mem, "peak_wset", mem.rss))
    stats["peak_memory_method"] = (
        "OS peak working set" if hasattr(mem, "peak_wset") else "sampled RSS"
    )
    stats["raw_zip_bytes"] = raw["size_bytes"]
    stats["raw_member_sha256"] = hasher.hexdigest()
    stats["source_event_types"] = dict(source_types)
    stats["selected_all_day_event_types"] = dict(selected_types)
    stats["rth_event_types"] = dict(rth_types)
    stats["source_display_codes"] = dict(displays)
    stats["source_frame_lengths"] = dict(frame_lengths)
    stats["source_symbols_with_adds"] = len(symbols)
    issue_names = (
        "locked",
        "crossed",
        "invalid_price",
        "off_grid_price",
        "negative_size",
        "zero_size",
        "duplicate_level",
        "level_order",
        "empty_bids",
        "empty_asks",
        "missing_promised_depth",
        "sub_grid_spread",
    )
    stats["all_day_issue_counts"] = {name: all_issues[name] for name in issue_names}
    stats["rth_issue_counts"] = {name: rth_issues[name] for name in issue_names}
    stats["rth_depth_distribution_bid_ask"] = dict(depths)
    stats["rth_add_price_gcd_units"] = selected_price_gcd
    stats["remaining_market_wide_orders_after_eof"] = len(book.orders)
    stats["remaining_selected_orders_after_eof"] = sum(
        o.symbol == cfg["symbol"] for o in book.orders.values()
    )
    stats["rth_top_n_updates_per_second_including_idle"] = stats["rth_book_changes"] / (
        (end - begin) / 1000
    )
    for updates in updates_second.values():
        distribution["updates_per_second_active_seconds"].add(updates)
    stats["rth_seconds_with_top_n_updates"] = len(updates_second)
    stats["distributions"] = {k: v.result() for k, v in distribution.items()}
    stats["trace_examples"] = len(traces)
    stats["artifacts"] = {}
    for name, writer in writers.items():
        destination = out / f"{name}.parquet"
        writer.path.replace(destination)
        stats["artifacts"][name] = {
            "path": destination.as_posix(),
            "rows": writer.count,
            "bytes": destination.stat().st_size,
            "sha256": sha256(destination),
        }
    (out / "lineage.json").write_text(
        json.dumps(
            {**lineage, "member_sha256": hasher.hexdigest(), "artifacts": stats["artifacts"]},
            indent=2,
        )
        + "\n"
    )
    (reports / "data_quality.json").write_text(json.dumps(stats, indent=2) + "\n")
    (reports / "data_quality_report.md").write_text(quality_markdown(stats), encoding="utf-8")
    write_traces(reports / "event_trace_examples.md", traces, raw["sha256"])
    status_path.write_text(
        json.dumps(
            {
                "status": "complete",
                "config_sha256": sha256(config_path),
                "raw_sha256": raw["sha256"],
                "quality_sha256": sha256(reports / "data_quality.json"),
            },
            indent=2,
        )
        + "\n"
    )
    print(
        json.dumps(
            {
                k: stats[k]
                for k in (
                    "source_messages",
                    "rth_events",
                    "rth_book_issue_states",
                    "processing_seconds",
                    "artifacts",
                )
            },
            indent=2,
        )
    )
    return stats


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config.yaml")
    args = parser.parse_args()
    run(args.config)


if __name__ == "__main__":
    main()
